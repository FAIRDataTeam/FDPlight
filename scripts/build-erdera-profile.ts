// Builds src/profiles/erdera/shapes/{type}.ttl from ERDERA's SHACL
// (src/profiles/erdera/source/, ERDERA/FDP-Reference-Implementation-Configuration,
// CC0): every ERDERA schema extends Resource, so each type's shapes are the
// Resource shape plus its own, as the RI's /{prefix}/spec serves them. The
// root takes the FAIR Data Point shapes of the default profile, without the
// Data Service ones (ERDERA removes that inheritance).
//
//   npx vite-node scripts/build-erdera-profile.ts

import { readFileSync, writeFileSync } from 'node:fs';
import { Parser } from 'n3';

const dir = 'src/profiles/erdera';
// dataset.ttl and distribution.ttl (ERDERA commit 4444c1a, unchanged since
// April 2025) are not valid Turtle. Two mechanical fixes, decided 2026-10-23:
// "] , sh:property [" repeats the predicate after a comma, corrected to ";";
// and one sh:name in dataset.ttl lacks its ";".
const MISSING_SEMICOLON = `sh:name "Personal Data? (leave this as the default if you don't know otherwise)"\n`;
const syntaxFix = (ttl: string) =>
  ttl
    .replace(/\]\s*,(\s*)sh:property\s*\[/g, '] ;$1sh:property [')
    .replace(MISSING_SEMICOLON, MISSING_SEMICOLON.replace('"\n', '" ;\n'));
const src = (f: string) => syntaxFix(readFileSync(`${dir}/source/${f}.ttl`, 'utf8'));

// The one change to ERDERA's shapes: FDPlight writes ejp:vpConnection
// ejp:VPDiscoverable unless a record is hidden (decided 2026-10-23, SPEC §8.4),
// so the field accepts both values instead of only ejp:VPInvisible.
const VP_ONLY = 'sh:in (<https://w3id.org/ejp-rd/vocabulary#VPInvisible>) ;';
const VP_BOTH = 'sh:in (<https://w3id.org/ejp-rd/vocabulary#VPDiscoverable> <https://w3id.org/ejp-rd/vocabulary#VPInvisible>) ;';
const resource = src('resource');
if (!resource.includes(VP_ONLY)) throw new Error('resource.ttl changed: the ejp:vpConnection sh:in list was not found');
const RESOURCE = resource.replace(VP_ONLY, `${VP_BOTH} # FDPlight: VPDiscoverable added`);

// FAIR Data Point shapes of the default profile (from home.fairdatapoint.org).
const fdp = readFileSync('src/profiles/fdp-default/shapes/fdp.ttl', 'utf8');
const start = fdp.indexOf('<http://fairdatapoint.org/FDPShape>');
const end = fdp.indexOf('<http://fairdatapoint.org/ResourceShape>');
if (start < 0 || end < start) throw new Error('fdp-default shapes changed: FDPShape / ResourceShape not found');
const prefixes = fdp.slice(0, fdp.search(/^<|^:/m)).split('\n').filter((l) => l.startsWith('@prefix')).join('\n');
const FDP_SHAPES = `${prefixes}\n\n${fdp.slice(start, end).trim()}\n`;

const header = (what: string) =>
  `# ERDERA profile, ${what}: generated by scripts/build-erdera-profile.ts from\n# ERDERA/FDP-Reference-Implementation-Configuration (CC0). Do not edit.\n\n`;

const TYPES: Record<string, string[]> = {
  fdp: ['FDP shapes'],
  catalog: ['catalog'],
  dataset: ['dataset'],
  distribution: ['distribution'],
  patientregistry: ['patient-registry'],
  biobank: ['biobank'],
  guideline: ['guideline'],
  dataservice: ['data-service'],
  dataservice2: ['data-service'],
};

for (const [key, parts] of Object.entries(TYPES)) {
  const own = parts.map((p) => (p === 'FDP shapes' ? FDP_SHAPES : src(p)));
  const ttl = header(`${key} (Resource + ${parts.join(' + ')})`) + [RESOURCE, ...own].join('\n\n');
  new Parser().parse(ttl); // must stay valid Turtle
  writeFileSync(`${dir}/shapes/${key}.ttl`, ttl);
  console.log(`${dir}/shapes/${key}.ttl`);
}
