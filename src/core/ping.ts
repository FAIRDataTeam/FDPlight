// The GitHub Action that pings the FDP Index (SPEC §7.2). FDPlight writes it
// with the Index and root URLs inline and regenerates it on every publish.

import { say } from './messages';

export const PING_WORKFLOW_PATH = '.github/workflows/fdp-ping.yml';

/** GitHub's own Pages workflow when Pages deploys from a branch. */
export const BRANCH_PAGES_WORKFLOW = 'pages-build-deployment';

export interface IndexSettings {
  /** The FDP Index to ping, e.g. https://home.fairdatapoint.org */
  url: string;
  /** Name of the workflow that deploys Pages; the ping runs after it. */
  pagesWorkflow: string;
}

const SAFE_URL = /^https:\/\/[^\s"'\\$`]+$/;
const SAFE_NAME = /^[^\n"\\$`]+$/;

/** Problems with the Index settings, empty when valid. */
export function validateIndex(index: IndexSettings): string[] {
  const errors: string[] = [];
  if (!SAFE_URL.test(index.url)) errors.push(say('indexUrl'));
  if (!SAFE_NAME.test(index.pagesWorkflow.trim())) errors.push(say('pagesWorkflow'));
  return errors;
}

/**
 * SPEC §7.2. The ping workflow for a project whose root entity is `rootIri`.
 * Runs after a successful Pages deployment, every three days (the Index marks
 * an FDP inactive after a week without a ping), and on demand.
 */
export function pingWorkflow(rootIri: string, index: IndexSettings): string {
  const errors = validateIndex(index);
  if (!SAFE_URL.test(rootIri)) errors.push('root IRI must be an https URL');
  if (errors.length) throw new Error(errors.join('; '));
  const indexUrl = index.url.replace(/\/+$/, '');
  return `# Generated by FDPlight on every publish: edits here are overwritten.
# Pings the FAIR Data Point Index so it harvests this FDP (FDPlight SPEC 7.2).
name: Ping FDP Index
on:
  workflow_run:
    workflows: ["${index.pagesWorkflow.trim()}"]
    types: [completed]
  schedule:
    - cron: "17 3 */3 * *"
  workflow_dispatch:
permissions: {}
jobs:
  ping:
    if: github.event_name != 'workflow_run' || github.event.workflow_run.conclusion == 'success'
    runs-on: ubuntu-latest
    steps:
      - name: Ping ${indexUrl}
        env:
          INDEX_URL: "${indexUrl}"
          ROOT_URL: "${rootIri}"
        run: |
          curl --fail -sS -X POST "$INDEX_URL" \\
            -H 'Content-Type: application/json' \\
            -d "{\\"clientUrl\\": \\"$ROOT_URL\\"}"
`;
}
